-- C06-8 직업 상태에 수감(PRISON) 추가 (2026-11-23, 유동현)
-- 윤아님 '위험한 제안'에서 붙잡히면 엔진이 JOB_STATUS = 'PRISON' 으로 저장하는데
-- CK_LIFE_JOB_STATUS 에 PRISON 이 없어 ORA-02290 (서버 500) 이 났음 → 허용 값에 PRISON 추가
-- 서버 재시작은 필요 없어요
ALTER TABLE LIFE DROP CONSTRAINT CK_LIFE_JOB_STATUS;

ALTER TABLE LIFE ADD CONSTRAINT CK_LIFE_JOB_STATUS
  CHECK (JOB_STATUS IN ('EMPLOYED','UNEMPLOYED','RETIRED','PRISON'));
